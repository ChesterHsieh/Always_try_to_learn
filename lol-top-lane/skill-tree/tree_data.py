import re as _re
_LET = "ABCD"


def _swap_letters(text, i, j):
    a, b = _LET[i], _LET[j]
    def sub(m):
        c = m.group(1)
        return b if c == a else (a if c == b else c)
    return _re.sub(r"(?<![A-Za-z0-9])([ABCD])(?![A-Za-z0-9])", sub, text)


